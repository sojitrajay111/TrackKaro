import type { Transaction } from "@/store/types";

const esc = (v: string) => v.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c] as string);
const inr = (n: number) => `₹${Math.round(n).toLocaleString("en-IN")}`;

/**
 * Opens a printable spending report for a date range in a new window and starts the print
 * dialog — "Save as PDF" there gives the PDF the app exports. Returns false if pop-ups are blocked.
 */
export function openPdfReport(opts: { from: string; to: string; name?: string; transactions: Transaction[] }): boolean {
  const { from, to, name, transactions } = opts;
  const rows = transactions.filter((t) => t.date && t.date.slice(0, 10) >= from && t.date.slice(0, 10) <= to).sort((a, b) => a.date.localeCompare(b.date));
  const income = rows.filter((t) => t.type === "income").reduce((s, t) => s + t.amount, 0);
  const spent = rows.filter((t) => t.type === "expense").reduce((s, t) => s + t.amount, 0);
  const byCat = new Map<string, number>();
  for (const t of rows) if (t.type === "expense") byCat.set(t.category, (byCat.get(t.category) ?? 0) + t.amount);
  const cats = [...byCat.entries()].sort((a, b) => b[1] - a[1]);

  const w = window.open("", "_blank");
  if (!w) return false;
  w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>TrackKaro report ${from} to ${to}</title>
<style>
body{font:13px/1.5 system-ui,-apple-system,"Segoe UI",sans-serif;color:#0c1f17;margin:32px}
h1{margin:0;font-size:24px}h2{font-size:15px;margin:24px 0 8px}p{margin:2px 0 0;color:#45594f}
.tiles{display:grid;grid-template-columns:repeat(3,1fr);gap:10px;margin-top:18px}
.tile{border:1px solid #dbe7df;border-radius:12px;padding:10px 12px}.tile b{display:block;font-size:20px}
table{width:100%;border-collapse:collapse}th,td{padding:6px 8px;border-bottom:1px solid #e3ece6;text-align:left}
th{font-size:11px;text-transform:uppercase;color:#62766c}.r{text-align:right}.in{color:#047857}
footer{margin-top:24px;font-size:11px;color:#62766c}@media print{body{margin:16px}}
</style></head><body>
<h1>Spending report</h1><p>${esc(name ? `${name} · ` : "")}${esc(from)} to ${esc(to)}</p>
<div class="tiles"><div class="tile">Money in<b class="in">${inr(income)}</b></div><div class="tile">Spent<b>${inr(spent)}</b></div>
<div class="tile">Net<b class="${income - spent >= 0 ? "in" : ""}">${income - spent < 0 ? "−" : ""}${inr(Math.abs(income - spent))}</b></div></div>
<h2>Spending by category</h2>
<table><thead><tr><th>Category</th><th class="r">Amount</th><th class="r">Share</th></tr></thead><tbody>
${cats.map(([c, v]) => `<tr><td>${esc(c)}</td><td class="r">${inr(v)}</td><td class="r">${spent ? Math.round((v / spent) * 100) : 0}%</td></tr>`).join("") || `<tr><td colspan="3">No spending in this range.</td></tr>`}
</tbody></table>
<h2>Transactions (${rows.length})</h2>
<table><thead><tr><th>Date</th><th>Title</th><th>Category</th><th>Method</th><th class="r">Amount</th></tr></thead><tbody>
${rows.map((t) => `<tr><td>${esc(t.date.slice(0, 10))}</td><td>${esc(t.title)}</td><td>${esc(t.category)}</td><td>${esc(t.paymentMethod || "")}</td><td class="r ${t.type === "income" ? "in" : ""}">${t.type === "income" ? "+" : "−"}${inr(t.amount)}</td></tr>`).join("") || `<tr><td colspan="5">No transactions in this range.</td></tr>`}
</tbody></table>
<footer>Generated by TrackKaro on ${esc(new Date().toLocaleString("en-IN"))}</footer>
<script>window.onload=function(){window.print()}</script></body></html>`);
  w.document.close();
  return true;
}
